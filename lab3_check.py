def check_stage1():
    """Find the Open Camera button, click it, and see what it starts."""
    try:
        import tkinter as tk
        from turbopi import gui as gui_module
        from turbopi.rosbridge_client import RosbridgeClient
    except ModuleNotFoundError as e:
        return [f"could not import your Lab 2 code ({e}). vision.py and lab3_check.py must be "
                "in your Lab_2 folder (next to run_robot.py), and you must run from there."]
    try:
        root = tk.Tk()
    except tk.TclError:
        return ["skipped - no display available (run the check on a computer with a screen)"]
    root.withdraw()
    try:
        with LaunchRecorder() as rec:       # nothing may start while the window is built
            gui_module.TeleopGUI(root, RosbridgeClient("127.0.0.1", 1), start=False)
        if rec.calls:
            return ["vision.py is started while the window is still being BUILT, not when the "
                    "button is clicked. Did you write command=self.your_method() with brackets? "
                    "(Lab 2, TODO 1A had the same trap.)"]
        buttons, todo = [], [root]
        while todo:
            w = todo.pop()
            todo.extend(w.winfo_children())
            if isinstance(w, tk.Button) and "camera" in str(w.cget("text")).lower():
                buttons.append(w)
        if not buttons:
            raise NotStarted
        btn = buttons[0]
        problems = []
        if btn.cget("text").strip().lower() != "open camera":
            problems.append(f'the button should say "Open Camera", it says {btn.cget("text")!r}')
        w = btn
        while w is not None and w is not root:
            if not w.winfo_manager():
                problems.append("the button is created but never put on screen (.pack() or .grid())")
                break
            w = w.master
        problems += click_and_watch(btn)
        return problems
    finally:
        root.destroy()


class LaunchRecorder:
    """While active, every way of starting a program - and importing vision
    to call it directly - is replaced by a recorder, so nothing really runs.
    What was attempted ends up in self.calls as (how, args) pairs."""

    def __enter__(self):
        calls = self.calls = []

        class FakePopen:
            def __init__(self, args, *a, **k):
                calls.append(("Popen", args))
                self.args, self.pid, self.returncode = args, 12345, None
            def poll(self):
                return None
            def wait(self, timeout=None):
                return 0
            def communicate(self, *a, **k):
                return b"", b""
            def terminate(self):
                pass
            kill = terminate

        def blocking(name):
            def fake(args=None, *a, **k):
                calls.append((name, args))
                return 0 if name == "os.system" else subprocess.CompletedProcess(args, 0, b"", b"")
            return fake

        class FakeVision(types.ModuleType):
            """Stands in for vision.py if the GUI imports it and calls it directly."""
            def __getattr__(self, attr):
                def fake(*a, **k):
                    calls.append(("in-process", f"vision.{attr}()"))
                return fake

        self.saved = {
            (subprocess, "Popen"): subprocess.Popen, (subprocess, "run"): subprocess.run,
            (subprocess, "call"): subprocess.call, (subprocess, "check_call"): subprocess.check_call,
            (subprocess, "check_output"): subprocess.check_output, (os, "system"): os.system,
        }
        self.real_vision = sys.modules.get("vision")
        subprocess.Popen = FakePopen
        for name in ("run", "call", "check_call", "check_output"):
            setattr(subprocess, name, blocking(f"subprocess.{name}"))
        os.system = blocking("os.system")
        sys.modules["vision"] = FakeVision("vision")
        return self

    def __exit__(self, *exc):
        for (mod, name), value in self.saved.items():
            setattr(mod, name, value)
        if self.real_vision is not None:
            sys.modules["vision"] = self.real_vision
        else:
            sys.modules.pop("vision", None)
        return False


def click_and_watch(btn):
    """Click the button under a LaunchRecorder. Returns problems."""
    with LaunchRecorder() as rec:
        start = time.time()
        try:
            btn.invoke()
        except Exception as e:
            if not rec.calls:
                return [f"clicking the button {crash_message(e)}"]
        took = time.time() - start
    calls = rec.calls

    if not calls:
        return ["clicking the button did not start vision.py"]
    kind, args = calls[0]
    text = " ".join(map(str, args)) if isinstance(args, (list, tuple)) else str(args)
    if kind == "in-process":
        return [f"the button runs vision.py INSIDE the GUI ({args}). Its camera loop never "
                "returns, so the window freezes and publish_loop stops. Run it as a separate "
                "program instead (README, Stage 1)."]
    if kind != "Popen":
        return [f"the button uses {kind}(), which WAITS until vision.py is closed - the GUI "
                "freezes and publish_loop stops meanwhile. Look for a way to start a program "
                "without waiting for it (README, Stage 1)."]
    if "vision.py" not in text:
        return [f"the button starts {text!r}, not vision.py"]
    if took > 1.0:
        return [f"clicking the button took {took:.1f} s - the GUI is frozen while it runs"]
    return []


def check_step1():
    vision = load_vision()
    img = blank()
    draw_shape(img, "square", TEST_BGR["red"][0], (200, 200), 40)
    with tempfile.TemporaryDirectory() as d:
        path = os.path.join(d, "test.jpg")
        cv2.imwrite(path, img)
        src = vision.open_source(path)
        if src is None:
            raise NotStarted
        if isinstance(src, np.ndarray):
            frame = src
        elif hasattr(src, "read"):
            ok, frame = src.read()
            if hasattr(src, "release"):
                src.release()
            if not ok:
                return ["open_source(<an image file>).read() returned ok = False"]
        else:
            return [f"open_source() should return something with .read() (like cv2.VideoCapture) "
                    f"or an image, got {type(src).__name__}"]
    if not isinstance(frame, np.ndarray) or frame.shape != img.shape:
        return [f"the frame from an image file should have shape {img.shape}, "
                f"got {getattr(frame, 'shape', type(frame).__name__)}"]
    return []


def mask_scene():
    """One object per test colour, plus white and black patches, on grey.
    Returns (BGR image, {colour name: region where that colour was drawn})."""
    img, where = blank(), {}
    spots = iter([(90, 110), (250, 110), (410, 110), (560, 110), (170, 300)])
    for name, shades in TEST_BGR.items():
        for bgr in shades:
            centre = next(spots)
            draw_shape(img, "square", bgr, centre, 45)
            where[name] = where.get(name, False) | region("square", centre, 45)
    cv2.rectangle(img, (330, 250), (440, 350), (255, 255, 255), -1)    # white paper
    cv2.rectangle(img, (480, 250), (590, 350), (15, 15, 15), -1)       # black shadow
    return img, where


def get_mask(vision, hsv, name):
    entry = colour_entry(vision, name)
    if entry is None:
        return None
    mask = vision.build_mask(hsv, entry)
    if mask is None:
        raise NotStarted
    if not isinstance(mask, np.ndarray) or mask.shape != hsv.shape[:2]:
        raise AssertionError(f"build_mask() should return a 2-D mask of shape {hsv.shape[:2]}, "
                             f"got {getattr(mask, 'shape', type(mask).__name__)}")
    return mask > 0


def check_step2():
    vision = load_vision()
    if not getattr(vision, "COLOURS", None):
        raise NotStarted
    img, where = mask_scene()
    hsv = cv2.cvtColor(img, cv2.COLOR_BGR2HSV)
    problems = []
    for name in REQUIRED_COLOURS:
        try:
            mask = get_mask(vision, hsv, name)
        except AssertionError as e:
            return [str(e)]
        if mask is None:
            problems.append(f'COLOURS has no entry with "name": "{name}"')
            continue
        for bgr in TEST_BGR[name]:
            obj = where[name] & np.all(img == bgr, axis=2)
            found = mask[grow(obj, -4)].mean()
            if found < 0.9:
                hint = ("  (red is on BOTH ends of the hue range - README, Step 2)"
                        if name == "red" and hsv_of(bgr)[0] > 90 else "")
                problems.append(f"{name}: only {found:.0%} of a {name} object (HSV {hsv_of(bgr)}) "
                                f"is white in its mask{hint}")
        others = ~grow(where[name], 4)
        stray = mask[others].mean()
        if stray > 0.01:
            problems.append(f"{name}: {stray:.0%} of the picture that is NOT {name} is white in its "
                            f"mask (grey HSV {hsv_of(BACKGROUND)}, white, black and the other colours "
                            "should all be black)")
    return problems


def check_step3():
    vision = load_vision()
    if colour_entry(vision, "red") is None:
        raise NotStarted
    rng = np.random.default_rng(1)
    img, red = blank(), TEST_BGR["red"][0]
    draw_shape(img, "square", red, (320, 240), 80)
    for x, y in ((280, 200), (350, 215), (300, 270), (360, 280), (320, 240)):   # holes in it
        cv2.rectangle(img, (x, y), (x + 2, y + 2), BACKGROUND, -1)
    specks = 0
    for x, y in rng.integers(10, 630, size=(60, 2)):                   # specks outside it
        if abs(x - 320) > 110 or abs(y - 240) > 110:
            cv2.rectangle(img, (int(x), int(y) % 470), (int(x) + 1, int(y) % 470 + 1), red, -1)
            specks += 1
    mask = get_mask(vision, cv2.cvtColor(img, cv2.COLOR_BGR2HSV), "red")
    obj = region("square", (320, 240), 80)
    problems = []
    left = int(mask[~grow(obj, 6)].sum())
    if left > 8:
        problems.append(f"{left} white pixels from {specks} tiny red specks survive in the mask - "
                        "clean it up (README, Step 3)")
    filled = mask[grow(obj, -3)].mean()
    if filled < 0.995:
        problems.append(f"small holes inside the object are not filled ({filled:.1%} white) "
                        "(README, Step 3)")
    return problems


CLASSIFY_CASES = [
    ("circle", "sphere"), ("square", "cube"),
    ("tilted square", "cube"), ("cube at an angle", "cube"),
]


def check_step4():
    vision = load_vision()
    problems, answers = [], []
    for kind, want in CLASSIFY_CASES:
        for size in (30, 60, 120):
            m = np.zeros((480, 640), np.uint8)
            draw_shape(m, kind, 255, (320, 240), size)
            contours, _ = cv2.findContours(m, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
            got = vision.classify_shape(contours[0])
            answers.append(got)
            if str(got).lower() != want:
                problems.append(f"a {kind} ({2 * size} px across) should be {want!r}, got {got!r}")
    if all(a is None for a in answers):
        raise NotStarted
    return problems


DETECT_SCENE = [    # (colour, shade index, drawn shape, expected label, centre, size)
    ("red", 0, "square", "cube", (110, 120), 50),
    ("blue", 0, "circle", "sphere", (320, 120), 55),
    ("green", 0, "tilted square", "cube", (520, 125), 45),
    ("yellow", 0, "circle", "sphere", (120, 350), 50),
    ("red", 1, "circle", "sphere", (320, 350), 45),
    ("blue", 0, "cube at an angle", "cube", (520, 350), 55),
]


def detect_scene():
    img = blank()
    for name, shade, kind, _, centre, size in DETECT_SCENE:
        draw_shape(img, kind, TEST_BGR[name][shade], centre, size)
    for x, y in ((230, 240), (420, 240), (40, 250), (600, 250)):       # specks: not objects
        cv2.rectangle(img, (x, y), (x + 2, y + 2), TEST_BGR["red"][0], -1)
    return img


def known(detections):
    return [d for d in detections if str(d.get("shape", "")).lower() != "unknown"]


def check_step5_detect():
    vision = load_vision()
    img = detect_scene()
    detections = vision.detect(img.copy())
    if detections is None:
        raise NotStarted
    if not isinstance(detections, list):
        return [f"detect() should return a list, got {type(detections).__name__}"]
    for d in detections:
        if not isinstance(d, dict) or not {"colour", "shape", "centre"} <= set(d):
            return ['each detection should be a dict with at least "colour", "shape" and '
                    f'"centre" keys, got {d!r:.120}']
    problems, unmatched = [], known(detections)
    for name, _, kind, label, centre, size in DETECT_SCENE:
        m = cv2.moments(region(kind, centre, size).astype(np.uint8))
        cx, cy = m["m10"] / m["m00"], m["m01"] / m["m00"]
        match = next((d for d in unmatched if colour_name(d) == name
                      and str(d["shape"]).lower() == label
                      and np.hypot(d["centre"][0] - cx, d["centre"][1] - cy) < 15), None)
        if match:
            unmatched.remove(match)
        else:
            problems.append(f"missed the {name} {label} at ({cx:.0f}, {cy:.0f})")
    for d in unmatched:
        problems.append(f"found a {colour_name(d)} {d['shape']} at {tuple(d['centre'])} "
                        "that isn't there")
    empty = blank()
    cv2.rectangle(empty, (100, 100), (300, 300), (255, 255, 255), -1)
    extra = known(vision.detect(empty) or [])
    if extra:
        problems.append(f"a picture with nothing coloured in it gave {len(extra)} detection(s)")
    return problems


def check_step5_draw():
    vision = load_vision()
    img = detect_scene()
    detections = vision.detect(img.copy())
    if not detections:
        raise NotStarted
    frame = img.copy()
    out = vision.draw_detections(frame, detections)
    drawn = not np.array_equal(frame, img) or (
        isinstance(out, np.ndarray) and out.shape == img.shape and not np.array_equal(out, img))
    if not drawn:
        raise NotStarted
    return []


CHECKS = [
    ("Setup",   "requirements.txt replaced with Lab 3's",          check_setup),
    ("Stage 1", "Open Camera button starts vision.py",            check_stage1),
    ("Step 1",  "open_source() opens an image file",              check_step1),
    ("Step 2",  "build_mask() finds each colour, nothing else",   check_step2),
    ("Step 3",  "build_mask() removes specks and fills holes",    check_step3),
    ("Step 4",  "classify_shape() tells cubes from spheres",      check_step4),
    ("Step 5",  "detect() finds and labels every object",         check_step5_detect),
    ("Step 5",  "draw_detections() draws on the frame",           check_step5_draw),
]


def self_check():
    print("Lab 3 self-check (no robot needed)\n")
    states = []
    for part, title, fn in CHECKS:
        try:
            problems = fn()
            state = f"{len(problems)} problem(s)" if problems else "ok"
        except NotStarted:
            problems, state = [], "not done yet"
        except Exception as e:                      # a crash in student code
            problems, state = [crash_message(e)], "1 problem(s)"
        print(f"{part:<8} {title:<50} {state}")
        for p in problems:
            print(f"         FAIL: {p}")
        states.append(state)
    print()
    if all(s == "ok" for s in states):
        print("All checks pass. Now make it work on the robot: README, Step 6.")
    else:
        print("Work through the steps in order; run --check again after each one.")
    return 0 if all(s == "ok" for s in states) else 1


if __name__ == "__main__":
    sys.exit(self_check())
