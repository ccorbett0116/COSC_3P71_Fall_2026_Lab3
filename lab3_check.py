REQUIRED_COLOURS = ("red", "green", "blue", "yellow")
BACKGROUND = (128, 128, 128)        # BGR, grey: no colour should match it

# BGR test colours. Red is tested on BOTH sides of the hue wrap-around.
TEST_BGR = {
    "red":     [(30, 30, 210), (60, 20, 200)],     # hue ~0 and hue ~173
    "green":   [(40, 170, 40)],
    "blue":    [(200, 80, 30)],
    "yellow":  [(30, 210, 220)],
}


def hsv_of(bgr):
    return tuple(int(v) for v in cv2.cvtColor(np.uint8([[bgr]]), cv2.COLOR_BGR2HSV)[0, 0])


# ---------- drawing the test pictures ----------

def shape_points(kind, centre, size):
    """Outline of a test shape, as an int32 polygon (circles are drawn separately)."""
    cx, cy = centre
    if kind == "square":
        pts = [(-1, -1), (1, -1), (1, 1), (-1, 1)]
    elif kind == "tilted square":          # a cube face-on, rotated 30 degrees
        a = np.radians(30)
        pts = [(np.cos(a + t) * 1.41, np.sin(a + t) * 1.41)
               for t in np.radians([45, 135, 225, 315])]
    elif kind == "cube at an angle":       # front face + a strip of top face: a hexagon
        pts = [(-0.8, -0.5), (-0.5, -0.9), (0.9, -0.9), (0.9, 0.5), (0.6, 0.9), (-0.8, 0.9)]
    else:
        raise ValueError(kind)
    return np.int32([(cx + x * size, cy + y * size) for x, y in pts])


def draw_shape(img, kind, colour, centre, size):
    if kind == "circle":
        cv2.circle(img, centre, size, colour, -1)
    else:
        cv2.fillPoly(img, [shape_points(kind, centre, size)], colour)


def blank(h=480, w=640):
    return np.full((h, w, 3), BACKGROUND, np.uint8)


def region(kind, centre, size, h=480, w=640):
    """Boolean mask of where a shape was drawn."""
    m = np.zeros((h, w), np.uint8)
    draw_shape(m, kind, 255, centre, size)
    return m > 0


def grow(mask, px):
    k = np.ones((2 * abs(px) + 1, 2 * abs(px) + 1), np.uint8)
    m = mask.astype(np.uint8)
    return (cv2.dilate(m, k) if px > 0 else cv2.erode(m, k)) > 0


# ---------- helpers ----------

class NotStarted(Exception):
    """The function still returns None: that step hasn't been started."""


def crash_message(e):
    """One line saying what went wrong, and where in vision.py (or gui.py)."""
    where = ""
    for frame in reversed(traceback.extract_tb(e.__traceback__)):
        name = os.path.basename(frame.filename)
        if name in ("vision.py", "gui.py"):
            where = f" (line {frame.lineno} of {name}: {frame.line})"
            break
    return f"crashed with {type(e).__name__}: {e}{where}"


def load_vision():
    if "vision" in sys.modules:
        return sys.modules["vision"]
    import vision
    return vision


def colour_entry(vision, name):
    """The COLOURS entry called `name`, or None."""
    for c in getattr(vision, "COLOURS", None) or []:
        if isinstance(c, dict) and str(c.get("name", "")).lower() == name:
            return c
    return None


def colour_name(d):
    c = d.get("colour")
    if isinstance(c, dict):
        c = c.get("name")
    return str(c).lower()


